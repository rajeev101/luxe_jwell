window.veloraProductLookup = Object.fromEntries(window.veloraProducts.map((product) => [product.id, product]));

window.formatPrice = function formatPrice(value) {
  return new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 0,
  }).format(value);
};

window.buildWhatsAppLink = function buildWhatsAppLink(productName) {
  const message = `Hello VELORA, I am interested in ${productName}. Please share the price and availability.`;
  return `https://wa.me/919589579306?text=${encodeURIComponent(message)}`;
};

